void QtBridge::openUrl(const QUrl& p){
    if(!p.isLocalFile())return;
    auto done=app_.open(std::filesystem::path(p.toLocalFile().toStdWString()));
    if(done){referenceUrl_={};referenceFeedback_=tr("Reference previews are not stored in .draw projects. Reimport the source image to compare.");}
    emit changed();
}
